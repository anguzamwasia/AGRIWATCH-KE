def clean_value(v):
    return float(v.replace(',', ''))

def process_data(raw_text, crop):
    records = []
    lines = [line.strip() for line in raw_text.split('\n') if line.strip()]
    for line in lines:
        parts = re.split(r'\t+', line)
        if len(parts) < 11:
            # Maybe spaces instead of tabs
            parts = re.split(r'\s{2,}', line)
            
        if len(parts) >= 11:
            county = parts[0].strip()
            for i, year in enumerate([2021, 2022, 2023, 2024, 2025]):
                area = clean_value(parts[1 + i*2])
                prod = clean_value(parts[2 + i*2])
                records.append({
                    "county": county,
                    "crop": crop,
                    "year": year,
                    "area_ha": area,
                    "production_tons": prod
                })
    return records

all_records = process_data(maize_raw, "Maize") + process_data(wheat_raw, "Wheat")
df = pd.DataFrame(all_records)
df['yield_tha'] = df['production_tons'] / df['area_ha']
# handle div by zero
df['yield_tha'] = df['yield_tha'].fillna(0)
df.to_csv("afa_official_stats.csv", index=False)
print(f"Generated afa_official_stats.csv with {len(df)} records.")
